//! Phase 8 JDBC databases through the whole backend: the driver catalog
//! with JDBC drivers, then on embedded H2, Derby and HyperSQL (no server):
//! a session, the explorer from `DatabaseMetaData`, DDL generated from the
//! introspected model and run again (round trip), text execution plans.
//! `FERRODB_TCK_ORACLE` (URL, see the TCK) adds Oracle: structured plans,
//! introspection with sequences and packages, the same DDL round trip.
//!
//! Runs when Java ≥ 17, `ferrodb-jdbc-host.jar` and the jars are present
//! (`FERRODB_TCK_JDBC=1` downloads the jars into `target/ferrodb-drivers-test`).

#![allow(clippy::disallowed_methods)]

use std::path::Path;

use ferrodb_api::*;
use futures::executor::block_on;

use crate::{CoreBackend, CoreOptions};

fn core(dir: &Path) -> CoreBackend {
    CoreBackend::new(CoreOptions {
        config_dir: Some(dir.join("config")),
        data_dir: Some(dir.join("data")),
        drivers_dir: Some(ferrodb_jdbc::testing::drivers_dir()),
        jdbc_host_jar: ferrodb_jdbc::find_host_jar(),
        ..CoreOptions::in_memory()
    })
    .unwrap()
}

fn source(id: &str, driver: &str, props: &[(&str, String)]) -> DataSourceConfig {
    DataSourceConfig {
        id: id.into(),
        name: id.into(),
        driver: driver.into(),
        folder: vec![],
        environment: Environment::Development,
        read_only: false,
        tx_mode: TxMode::Auto,
        properties: props
            .iter()
            .map(|(k, v)| ((*k).to_owned(), v.clone()))
            .collect(),
        secret_ref: None,
    }
}

fn run(core: &CoreBackend, s: SessionId, text: &str) {
    let h = core.queries().execute(
        s,
        Script::new(text),
        ExecOptions {
            mode: ExecMode::WholeScript,
            ..Default::default()
        },
    );
    let errs: Vec<String> = block_on(async {
        let mut errs = Vec::new();
        while let Ok(ev) = h.events.recv().await {
            match ev {
                QueryEvent::Error(q) => errs.push(q.to_string()),
                QueryEvent::Finished => break,
                _ => {}
            }
        }
        errs
    });
    assert!(errs.is_empty(), "{text}: {errs:?}");
}

#[test]
fn catalog_lists_jdbc_drivers() {
    let dir = tempfile::tempdir().unwrap();
    let c = CoreBackend::new(CoreOptions {
        drivers_dir: Some(dir.path().join("drivers")),
        ..CoreOptions::in_memory()
    })
    .unwrap();
    let list = c.drivers().list();
    for id in [
        "oracle", "db2", "sybase", "h2", "derby", "hsqldb", "exasol", "vertica", "hive",
    ] {
        let d = list
            .iter()
            .find(|d| d.id.as_str() == id)
            .unwrap_or_else(|| panic!("{id}"));
        assert_eq!(d.family.as_str(), "jdbc");
        assert_eq!(d.access(), AccessLayer::Jdbc);
    }
    let oracle: DriverId = "oracle".into();
    assert_eq!(c.drivers().status(&oracle), DriverStatus::NotDownloaded);
    assert_eq!(c.drivers().versions(&oracle)[0], "23.26.4.0.0");
    assert_eq!(
        c.drivers().status(&"postgresql".into()),
        DriverStatus::BuiltIn
    );
    assert_eq!(c.drivers().jdbc_bridge(), BridgeState::NotStarted);
    // Custom files (level C) for the generic JDBC driver.
    let jar = dir.path().join("my-driver.jar");
    std::fs::write(&jar, b"not really a jar").unwrap();
    let events = c.drivers().subscribe();
    block_on(c.drivers().use_custom_artifacts(&"jdbc".into(), vec![jar])).unwrap();
    assert_eq!(
        c.drivers().status(&"jdbc".into()),
        DriverStatus::Custom { files: 1 }
    );
    assert!(matches!(
        events.try_recv(),
        Ok(DriverEvent::StatusChanged(..))
    ));
    // Connecting without the driver files says what is missing.
    block_on(c.data_sources().save(
        source("ora", "oracle", &[("host", "localhost".into())]),
        SecretValues::new(),
    ))
    .unwrap();
    let e = block_on(c.data_sources().connect(&"ora".into())).unwrap_err();
    assert!(matches!(e, Error::DriverMissing(_)), "{e:?}");
}

/// Shop schema in each embedded database's SQL.
const SHOP: &str = "
create table customers (id integer generated by default as identity primary key, email varchar(100) not null, created timestamp default current_timestamp);
create table orders (id integer not null primary key, customer_id integer constraint fk_cust references customers(id) on delete cascade, total decimal(10,2), note varchar(200));
create index ix_orders_total on orders (total);
create view big_orders as select id, total from orders where total > 10;
create sequence seq_orders start with 10 increment by 5;
insert into customers (id, email) values (1, 'a@x'), (2, 'b@x');
insert into orders values (1, 1, 10, 'x'), (2, 2, 20, 'y'), (3, 1, 5, 'z');
";

fn node(ds: &str, path: &[(ObjectKind, &str)]) -> NodeRef {
    let mut n = NodeRef::root(ds.into());
    for (k, name) in path {
        n = n.child(*k, *name);
    }
    n
}

fn names(objs: &[DbObject]) -> Vec<String> {
    objs.iter().map(|o| o.name.clone()).collect()
}

/// Explorer, DDL round trip and plans on one embedded database.
fn embedded(id: &str, user: &str, schema: &str) {
    if let Err(why) = ferrodb_jdbc::testing::bridge(&[id]) {
        eprintln!("{id}: skipped: {why}");
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    let c = core(dir.path());
    let db = dir.path().join(format!("{id}-db"));
    block_on(c.data_sources().save(
        source(
            id,
            id,
            &[
                ("mode", "embedded".into()),
                ("database", db.to_string_lossy().into_owned()),
                ("user", user.into()),
            ],
        ),
        SecretValues::new(),
    ))
    .unwrap();
    let s = block_on(c.queries().open_session(&id.into())).unwrap();
    run(&c, s, SHOP);
    assert!(matches!(
        c.drivers().jdbc_bridge(),
        BridgeState::Running { .. }
    ));

    // Explorer from DatabaseMetaData.
    let root = block_on(c.metadata().children(NodeRef::root(id.into()))).unwrap();
    assert!(names(&root).iter().any(|n| n == schema), "{id}: {root:?}");
    let sch = node(id, &[(ObjectKind::Schema, schema)]);
    let objs = block_on(c.metadata().children(sch.clone())).unwrap();
    let objs = names(&objs);
    for want in ["CUSTOMERS", "ORDERS", "BIG_ORDERS", "SEQ_ORDERS"] {
        assert!(objs.iter().any(|n| n == want), "{id}: {want} in {objs:?}");
    }
    let orders = node(
        id,
        &[(ObjectKind::Schema, schema), (ObjectKind::Table, "ORDERS")],
    );
    let cols = block_on(c.metadata().children(orders.clone())).unwrap();
    assert!(
        names(&cols).contains(&"CUSTOMER_ID".to_owned()),
        "{id}: {cols:?}"
    );

    // DDL from the model, run again after dropping everything.
    let objects = vec![
        node(
            id,
            &[
                (ObjectKind::Schema, schema),
                (ObjectKind::Table, "CUSTOMERS"),
            ],
        ),
        orders.clone(),
        node(
            id,
            &[
                (ObjectKind::Schema, schema),
                (ObjectKind::View, "BIG_ORDERS"),
            ],
        ),
        node(
            id,
            &[
                (ObjectKind::Schema, schema),
                (ObjectKind::Sequence, "SEQ_ORDERS"),
            ],
        ),
    ];
    let ddl = block_on(c.metadata().definition(objects, DdlOptions::default())).unwrap();
    assert!(ddl.contains("FOREIGN KEY"), "{id}: {ddl}");
    assert!(
        ddl.contains("GENERATED BY DEFAULT AS IDENTITY"),
        "{id}: {ddl}"
    );
    assert!(ddl.contains("CREATE INDEX"), "{id}: {ddl}");
    // Derby's DROP SEQUENCE needs RESTRICT.
    let restrict = if id == "derby" { " restrict" } else { "" };
    run(
        &c,
        s,
        &format!(
            "drop view big_orders; drop table orders; drop table customers; drop sequence seq_orders{restrict}"
        ),
    );
    run(&c, s, &ddl);
    block_on(c.metadata().refresh(&id.into(), RefreshScope::All)).unwrap();
    let cols2 = block_on(c.metadata().children(orders)).unwrap();
    assert_eq!(
        names(&cols),
        names(&cols2),
        "{id}: columns after the round trip\n{ddl}"
    );
    run(&c, s, "insert into customers (email) values ('c@x')");

    // Text plans.
    let plan = block_on(c.queries().explain(
        s,
        Script::new("select * from orders where total > 1"),
        ExplainOptions::default(),
    ))
    .unwrap();
    assert!(!plan.root.children.is_empty(), "{id}: {plan:?}");
    println!("{id} plan:\n{}", plan.raw);
}

