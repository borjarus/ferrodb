/// Oracle: `FERRODB_TCK_ORACLE=oracle://tck:ferrodb@localhost:56121/FREEPDB1`.
#[test]
fn oracle_server() {
    let Ok(url) = std::env::var("FERRODB_TCK_ORACLE") else {
        return;
    };
    if let Err(why) = ferrodb_jdbc::testing::bridge(&["oracle"]) {
        eprintln!("oracle: skipped: {why}");
        return;
    }
    let cfg = ferrodb_drivers::ResolvedConfig::from_url("oracle", &url).unwrap();
    let dir = tempfile::tempdir().unwrap();
    let c = core(dir.path());
    let user = cfg.user().unwrap_or("tck").to_owned();
    let schema = user.to_ascii_uppercase();
    block_on(c.data_sources().save(
        source(
            "ora",
            "oracle",
            &[
                ("host", cfg.host().to_owned()),
                ("port", cfg.port(1521).unwrap().to_string()),
                ("database", cfg.database().unwrap_or("FREEPDB1").to_owned()),
                ("user", user.clone()),
                // The first connection also starts the JVM.
                ("option.connect_timeout", "120".into()),
            ],
        ),
        SecretValues::new().with("password", cfg.password().unwrap_or_default()),
    ))
    .unwrap();
    let s = block_on(c.queries().open_session(&"ora".into())).unwrap();
    // Leftovers of an earlier run.
    for drop in [
        "drop view big_orders",
        "drop table orders",
        "drop table customers",
        "drop sequence seq_orders",
        "drop package shop_pkg",
        "drop synonym clients",
    ] {
        let h = c
            .queries()
            .execute(s, Script::new(drop), ExecOptions::default());
        block_on(async {
            while let Ok(ev) = h.events.recv().await {
                if matches!(ev, QueryEvent::Finished) {
                    break;
                }
            }
        });
    }
    run(
        &c,
        s,
        "create table customers (id number(10) generated by default as identity primary key, email varchar2(100) not null, created timestamp default systimestamp);
         create table orders (id number(10) not null primary key, customer_id number(10) constraint fk_cust references customers(id) on delete cascade, total number(10,2), note varchar2(200));
         create index ix_orders_total on orders (total);
         create view big_orders as select id, total from orders where total > 10;
         create sequence seq_orders start with 10 increment by 5;
         create synonym clients for customers;
         insert into customers (email) values ('a@x');
         insert into orders values (1, 1, 10, 'x')",
    );
    // A PL/SQL unit is one statement; the console splitter of this build
    // does not know PL/SQL blocks yet, so it goes straight to the driver.
    {
        use ferrodb_drivers::Driver;
        let bridge = ferrodb_jdbc::testing::bridge(&["oracle"]).unwrap();
        let d =
            ferrodb_jdbc::JdbcDriver::new(ferrodb_jdbc::flavor("oracle").unwrap(), bridge.clone());
        let rt = tokio::runtime::Runtime::new().unwrap();
        rt.block_on(async {
            let mut conn = d.connect(&cfg).await.unwrap();
            ferrodb_drivers::sink::collect(
                conn.as_mut(),
                "create or replace package shop_pkg as procedure touch; end shop_pkg;",
                ferrodb_drivers::CancellationToken::new(),
            )
            .await
            .unwrap();
            drop(conn);
            bridge.shutdown().await;
        });
    }
    let sch = node("ora", &[(ObjectKind::Schema, &schema)]);
    let objs = names(&block_on(c.metadata().children(sch)).unwrap());
    for want in [
        "CUSTOMERS",
        "ORDERS",
        "BIG_ORDERS",
        "SEQ_ORDERS",
        "CLIENTS",
        "SHOP_PKG",
    ] {
        assert!(objs.iter().any(|n| n == want), "{want} in {objs:?}");
    }
    let orders = node(
        "ora",
        &[(ObjectKind::Schema, &schema), (ObjectKind::Table, "ORDERS")],
    );
    let objects = vec![
        node(
            "ora",
            &[
                (ObjectKind::Schema, &schema),
                (ObjectKind::Table, "CUSTOMERS"),
            ],
        ),
        orders.clone(),
        node(
            "ora",
            &[
                (ObjectKind::Schema, &schema),
                (ObjectKind::View, "BIG_ORDERS"),
            ],
        ),
        node(
            "ora",
            &[
                (ObjectKind::Schema, &schema),
                (ObjectKind::Sequence, "SEQ_ORDERS"),
            ],
        ),
    ];
    let ddl = block_on(c.metadata().definition(objects, DdlOptions::default())).unwrap();
    println!("{ddl}");
    let cols = names(&block_on(c.metadata().children(orders.clone())).unwrap());
    run(
        &c,
        s,
        "drop view big_orders; drop table orders; drop table customers; drop sequence seq_orders",
    );
    run(&c, s, &ddl);
    block_on(c.metadata().refresh(&"ora".into(), RefreshScope::All)).unwrap();
    assert_eq!(
        cols,
        names(&block_on(c.metadata().children(orders)).unwrap())
    );

    let plan = block_on(c.queries().explain(
        s,
        Script::new("select o.id, c.email from orders o join customers c on c.id = o.customer_id"),
        ExplainOptions::default(),
    ))
    .unwrap();
    println!("{}", plan.raw);
    assert_eq!(plan.root.operation, "SELECT STATEMENT");
    assert!(plan.root.cost > 0.0);
    assert!(!plan.root.children.is_empty());
}
